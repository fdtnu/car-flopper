            let nq = base.advanced(by: nv * 6).assumingMemoryBound(to: UInt16.self)
            for i in 0..<nv {
                norms[i*3+0] = Float(nq[i*3+0]) / 65535.0 * 2 - 1
                norms[i*3+1] = Float(nq[i*3+1]) / 65535.0 * 2 - 1
                norms[i*3+2] = Float(nq[i*3+2]) / 65535.0 * 2 - 1
            }
            let ip = base.advanced(by: nv * 12).assumingMemoryBound(to: UInt16.self)
            for i in 0..<nf * 3 { idx[i] = ip[i] }
        }
        let vData = Data(bytes: &verts, count: nv * 12)
        let nData = Data(bytes: &norms, count: nv * 12)
        let vSrc = SCNGeometrySource(data: vData, semantic: .vertex, vectorCount: nv,
                                     usesFloatComponents: true, componentsPerVector: 3,
                                     bytesPerComponent: 4, dataOffset: 0, dataStride: 12)
        let nSrc = SCNGeometrySource(data: nData, semantic: .normal, vectorCount: nv,
                                     usesFloatComponents: true, componentsPerVector: 3,
                                     bytesPerComponent: 4, dataOffset: 0, dataStride: 12)
        let iData = Data(bytes: &idx, count: nf * 6)
        let el = SCNGeometryElement(data: iData, primitiveType: .triangles,
                                    primitiveCount: nf, bytesPerIndex: 2)
        let geo = SCNGeometry(sources: [vSrc, nSrc], elements: [el])
        let m = SCNMaterial()
        m.diffuse.contents = UIColor(red: 0.18, green: 0.18, blue: 0.19, alpha: 1)
        m.roughness.contents = 0.92
        m.isDoubleSided = true
        geo.materials = [m]
        return SCNNode(geometry: geo)
    }
